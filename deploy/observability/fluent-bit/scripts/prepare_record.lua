-- ============================================================================
--  MindLex: подготовка записи журнала к отправке в Victoria Logs.
--
--  Фильтр решает две задачи:
--  1) Fluent Bit ведёт собственное время приёма записи и раскладывает события по нему,
--     а приложение присылает время события в поле `timestamp`. Здесь это значение
--     проверяется и переносится в поле `@timestamp`, которое указано в настройке
--     `_time_field`: так в хранилище попадает время события, а не время доставки.
--     Иначе запрос «за последние N минут» показывал бы неверные данные.
--  2) Уровень журнала приводится к верхнему регистру, чтобы фильтры вида level:ERROR
--     не зависели от регистра исходного значения.
--
--  Записи без времени события (баннер Spring Boot и служебные строки JVM в stdout)
--  отбрасываются: структурированного времени у них нет, и в хранилище журналов
--  они дают только шум.
-- ============================================================================

-- Проверяет, что строка похожа на время в формате ISO-8601: YYYY-MM-DDTHH:MM:SS[.mmm][Z|±hh:mm]
local function is_iso8601(value)
  if type(value) ~= "string" or #value < 19 then
    return false
  end
  return string.match(value, "^%d%d%d%d%-%d%d%-%d%dT%d%d:%d%d:%d%d") ~= nil
end

function prepare(_, timestamp, record)
  -- 0. Записи без времени события не отправляются: в stdout Java попадают ASCII-баннер
  --    Spring Boot и служебные строки JVM, и в хранилище журналов они дают только шум.
  --    Признак записи приложения — поле timestamp, которое пишет кодировщик журнала.
  local ts = record["timestamp"]
  if not is_iso8601(ts) then
    return -1
  end
  record["@timestamp"] = ts

  -- 1. Имя сервиса: у записей приложения оно уже есть (service.name = mindlex-api),
  --    значение по умолчанию подставляется на случай строк с другим набором полей.
  if record["service.name"] == nil then
    record["service.name"] = "mindlex-api"
  end

  -- 2. Уровень приводится к верхнему регистру, чтобы фильтры вида level:ERROR
  --    не зависели от регистра исходного значения.
  local level = record["level"]
  if type(level) == "string" and #level > 0 then
    record["level"] = string.upper(level)
  else
    record["level"] = "INFO"
  end

  return 1, timestamp, record
end
